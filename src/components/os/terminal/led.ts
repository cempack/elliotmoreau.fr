/** the accent row above a capital: acute, grave, circumflex, diaeresis */
const MARK: Record<string, number> = { "́": 0x02, "̀": 0x08, "̂": 0x04, "̈": 0x0a };

export type LedCell = { rows: number[]; mark: number };

/** text → cells for the board: capitals, accents kept above, unknown characters as a space */
export function ledCells(text: string): LedCell[] {
  const out: LedCell[] = [];
  const typo: Record<string, string> = { "’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-", "…": "...", "→": ">", "×": "X" };
  for (const raw of Array.from(text.toLocaleUpperCase("fr-FR"))) {
    const ch = typo[raw] ?? raw;
    if (ch.length > 1) {
      for (const c of ch) out.push({ rows: F[c] ?? F[" "], mark: 0 });
      continue;
    }
    const [base, ...marks] = Array.from(ch.normalize("NFD"));
    out.push({ rows: F[base] ?? F[" "], mark: marks.reduce((m, k) => m | (MARK[k] ?? 0), 0) });
  }
  return out;
}

/** dots per character, glyph and spacing */
export const LED_CELL = 6;
/** rows per text line: the accent row and seven */
export const LED_LINE = 8;
