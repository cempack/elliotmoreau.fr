import type { Cells } from "@/components/glyphs";

/** Parse "#"/"." rows into PixelGlyph cells (7 × 7 unless noted). */
function cells(rows: string[]): Cells {
  const out: Cells = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") out.push([x, y]);
  });
  return out;
}

